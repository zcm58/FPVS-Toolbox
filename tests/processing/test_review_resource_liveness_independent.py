def test_temporary_actual_commit_pressure_waits_explicitly_then_recovers(monkeypatch, tmp_path):
    attempts = 0

    def snapshot(submitted, _pools):
        nonlocal attempts
        if submitted:
            attempts += 1
        # Healthy6 + floor1 + margin1 fits8; actual9 + floor1 + margin1 needs11.
        return _snapshot(16, 12, commit=8 if attempts < 4 else 12)

    scan, pools, submitted, progress = _fake_run(
        monkeypatch, tmp_path, estimates=[_estimate(6 * GIB, 18 * GIB)],
        snapshots=snapshot, requests=[9 * GIB], ceiling=1,
    )
    assert not scan.cancelled and not scan.errors and submitted == [0]
    assert pools[0].status[0] == 1
    assert any("memory" in message.lower() and "wait" in message.lower() for message in progress)


_SPAWN_OWNERS = []
_SPAWN_POPULATIONS = []


class _SmallHostExecutor(ProcessPoolExecutor):
    def __init__(self, **kwargs):
        _SPAWN_POPULATIONS.append(kwargs["max_workers"])
        super().__init__(**kwargs)

    def shutdown(self, **kwargs):
        _SPAWN_OWNERS.extend((self._processes or {}).values())
        return super().shutdown(**kwargs)


def _spawn_scoring_request(info, _settings, *_args, job_index=None):
    process = psutil.Process()
    process_module._send_control_message({
        "type": "worker_started", "job_index": job_index,
        "pid": process.pid, "created": process.create_time(),
    })
    process_module._request_scoring_admission(
        job_index, 65, info.samples, 64, info.samples, False, 0,
    )
    return _result(info)


def _spawn_case(monkeypatch, tmp_path, *, impossible=False, unknown=False):
    _SPAWN_OWNERS.clear()
    _SPAWN_POPULATIONS.clear()
    count = 1 if impossible else 4
    estimate = _estimate(6 * GIB, 18 * GIB) if impossible else _estimate()
    infos = [SimpleNamespace(
        path=tmp_path / f"P{index}.bdf", subject_id=f"P{index}",
        recording_id=f"P{index}__session", session_id="session",
        session_label="Session", visit_index=1,
        samples=5_000_000 if impossible else 2_248_704,
    ) for index in range(count)]
    plan = process_module._ReviewResourcePlan(
        count, 12 * GIB, (GIB if unknown else estimate.healthy_bytes,) * count,
        estimates=(None if unknown else estimate,) * count, exclusive=(unknown,) * count,
        emergency_bytes=0 if unknown else GLOBAL_E, dynamic=True,
    )
    monkeypatch.setattr(process_module, "_review_resource_plan", lambda *_a, **_kw: plan)
    monkeypatch.setattr(process_module, "ProcessPoolExecutor", _SmallHostExecutor)
    if not unknown:
        monkeypatch.setattr(process_module, "_run_one_review", _spawn_scoring_request)
    monkeypatch.setattr(process_module, "probe_owned_memory", lambda *_: OwnedMemory())
    monkeypatch.setattr(process_module, "probe_memory_snapshot", lambda: _snapshot(16, 12 if impossible else 10))
    cancelled = Event()
    watchdog = Timer(25, cancelled.set)
    watchdog.start()
    try:
        scan = process_module.run_process_review(infos, {}, event_map={}, should_cancel=cancelled.is_set)
    finally:
        watchdog.cancel()
    assert not cancelled.is_set() and not scan.cancelled
    assert _SPAWN_POPULATIONS and set(_SPAWN_POPULATIONS) == {1}
    assert _SPAWN_OWNERS and all(not process.is_alive() for process in _SPAWN_OWNERS)
    return scan


def test_real_spawned_16gib_serial_fallback_transport_finishes_and_releases_owners(monkeypatch, tmp_path):
    scan = _spawn_case(monkeypatch, tmp_path)
    assert not scan.errors and len(scan.results) == 4
    assert [row.recording_id for row in scan.results] == [f"P{i}__session" for i in range(4)]


def test_real_spawned_impossible_actual_request_is_actionable_and_releases_owner(monkeypatch, tmp_path):
    scan = _spawn_case(monkeypatch, tmp_path, impossible=True)
    assert len(scan.errors) == 1
    assert "physical host capacity" in scan.errors[0].error


def test_all_unknown_exclusive_sources_use_one_native_worker_and_keep_ordered_errors(monkeypatch, tmp_path):
    # Missing BDFs enter the unchanged ordinary scanner; no waveform exists.
    scan = _spawn_case(monkeypatch, tmp_path, unknown=True)
    assert len(scan.errors) == 4
    assert [row.recording_id for row in scan.errors] == [f"P{i}__session" for i in range(4)]
    assert all(row.error for row in scan.errors)
