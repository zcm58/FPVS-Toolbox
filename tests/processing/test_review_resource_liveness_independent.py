def test_solo_submission_rechecks_ram_decline_after_pool_construction(monkeypatch, tmp_path):
    available, low_samples, introduced_pressure = 6, 0, False

    def pool_created():
        nonlocal available, low_samples, introduced_pressure
        if not introduced_pressure:
            introduced_pressure = True
            available, low_samples = 3, 3

    def snapshot(*_args):
        nonlocal available, low_samples
        if low_samples:
            low_samples -= 1
        else:
            available = 6
        return _snapshot(16, available)

    def admitted():
        assert available == 6, "Solo work was submitted after RAM fell below its healthy credit."

    scan, _pools, submitted, progress = _fake_run(
        monkeypatch, tmp_path, estimates=[_estimate()] * 2,
        snapshots=snapshot, ceiling=2, on_pool_created=pool_created,
        before_submit=admitted,
    )
    assert not scan.errors and submitted == [0, 1]
    assert any("waiting" in message.lower() for message in progress)


