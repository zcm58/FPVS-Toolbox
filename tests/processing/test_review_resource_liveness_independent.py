GIB = 1024**3
# Header-only retained P6 follicular geometry. These are observation constants,
# not values generated by the implementation under test.
SMALL_H = 2_537_422_848
SMALL_FULL = 8_077_344_768
SMALL_E = 5_539_921_920
GLOBAL_E = 9_921_576_960


def _estimate(healthy=SMALL_H, full=SMALL_FULL):
    return ReviewMemoryEstimate(healthy, healthy, full, healthy,
                                max(0, full - healthy), ())


def _result(info):
    return KurtosisReviewScan((KurtosisReviewFileResult(
        path=info.path, participant_id=info.subject_id,
        recording_id=info.recording_id, session_id=info.session_id,
        session_label=info.session_label, visit_index=info.visit_index,
        status=KURTOSIS_REVIEW_FILE_STATUS_CLEAR,
    ),))


class _ControlQueue(Queue):
    closed = False
    joined = False

    def close(self):
        self.closed = True

    def join_thread(self):
        self.joined = True


class _Context:
    def __init__(self):
        self.messages = _ControlQueue()

    def Event(self):
        return Event()

    def Queue(self, **_kwargs):
        return self.messages

    def Array(self, _type, values):
        return list(values)


class _NotifiedFuture(Future):
    def cancel(self):
        was_cancelled = self.cancelled()
        cancelled = super().cancel()
        if cancelled and not was_cancelled:
            self.set_running_or_notify_cancel()
        return cancelled


def _fake_run(monkeypatch, tmp_path, *, estimates, snapshots, requests=(), ceiling=4,
              emergency=GLOBAL_E, observe=None, watchdog_seconds=2,
              on_pool_created=None, before_submit=None):
    context, pools, submitted, request_futures, progress = _Context(), [], [], {}, []
    infos = [SimpleNamespace(
        path=tmp_path / f"P{index}.bdf", subject_id=f"P{index}",
        recording_id=f"P{index}__session", session_id="session",
        session_label="Session", visit_index=1,
    ) for index in range(len(estimates))]
    plan = process_module._ReviewResourcePlan(
        ceiling, 12 * GIB, tuple(item.healthy_bytes for item in estimates),
        estimates=tuple(estimates), exclusive=(False,) * len(estimates),
        emergency_bytes=emergency, dynamic=True,
    )

    class Executor:
        closed = False

        def __init__(self, **kwargs):
            assert all(pool.closed for pool in pools), "A drained pool must close before replacement."
            self.population = kwargs["max_workers"]
            self.events, self.status = kwargs["initargs"][2:4]
            pools.append(self)
            if on_pool_created is not None:
                on_pool_created()

        def submit(self, _function, info, *_args, job_index=None):
            if before_submit is not None:
                before_submit()
            submitted.append(job_index)
            pid = 12000 + len(pools) * 100 + job_index % self.population
            context.messages.put({"type": "worker_started", "job_index": job_index,
                                  "pid": pid,
                                  "created": 10.0})
            future = _NotifiedFuture()
            if job_index < len(requests) and requests[job_index] is not None:
                context.messages.put({"type": "memory_request", "job_index": job_index,
                                      "required_bytes": requests[job_index],
                                      "pid": pid,
                                      "created": 10.0})
                request_futures[future] = (job_index, self)
            else:
                future.set_result(_result(info))
            return future

        def shutdown(self, **_kwargs):
            self.closed = True

    def wait_for_grants(futures, **_kwargs):
        for future in futures:
            if future in request_futures and not future.done():
                index, pool = request_futures[future]
                if pool.events[index].is_set():
                    if pool.status[index] == 1:
                        future.set_result(_result(infos[index]))
                    else:
                        future.set_exception(MemoryError("Actual scoring cannot fit host physical capacity."))
        return native_wait(futures, timeout=0.001)

    monkeypatch.setattr(process_module, "_review_resource_plan", lambda *_a, **_kw: plan)
    monkeypatch.setattr(process_module, "get_context", lambda _method: context)
    monkeypatch.setattr(process_module, "ProcessPoolExecutor", Executor)
    monkeypatch.setattr(process_module, "probe_owned_memory", lambda *_a: OwnedMemory())
    monkeypatch.setattr(process_module, "probe_memory_snapshot", lambda: snapshots(submitted, pools))
    monkeypatch.setattr(process_module, "wait", wait_for_grants)
    if observe is not None:
        original = process_module.memory_admission_fits

        def fits(snapshot, **kwargs):
            result = original(snapshot, **kwargs)
            observe(snapshot, kwargs, result, submitted, pools)
            return result

        monkeypatch.setattr(process_module, "memory_admission_fits", fits)
    cancelled = Event()
    watchdog = Timer(watchdog_seconds, cancelled.set)
    watchdog.start()
    try:
        scan = process_module.run_process_review(
            infos, {}, event_map={}, max_workers=ceiling,
            should_cancel=cancelled.is_set,
            progress=lambda message, *_counts: progress.append(message),
        )
    finally:
        watchdog.cancel()
    assert not cancelled.is_set(), "Admission made no progress before the bounded watchdog."
    assert context.messages.closed and context.messages.joined
    assert all(pool.closed for pool in pools)
    return scan, pools, submitted, progress


def _snapshot(total, available, commit=None):
    return ReviewMemorySnapshot(total * GIB, available * GIB,
                                (available if commit is None else commit) * GIB, True)


def test_real_header_small_host_reduces_four_pool_floors_and_completes_fallbacks(monkeypatch, tmp_path):
    observed = []
    scan, pools, submitted, _progress = _fake_run(
        monkeypatch, tmp_path, estimates=[_estimate()] * 4,
        snapshots=lambda *_: _snapshot(16, 10), requests=[SMALL_FULL] * 4,
        observe=lambda _snapshot, values, fit, *_: observed.append((values, fit)),
    )
    assert not scan.cancelled and not scan.errors
    assert submitted == [0, 1, 2, 3]
    assert all(pool.population == 1 for pool in pools)
    assert any(values["worker_count"] == 1 and fit for values, fit in observed)
    assert all(values["worker_count"] >= len(values["active_credits"]) for values, _fit in observed)
    assert [row.recording_id for row in scan.results] == [f"P{i}__session" for i in range(4)]


